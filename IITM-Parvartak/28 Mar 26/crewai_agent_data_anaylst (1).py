from langchain_community.tools import tool
from langchain_community.document_loaders import WebBaseLoader
from langchain_community.utilities import DuckDuckGoSearchAPIWrapper
import os

# Web Scraper Tool
@tool("Website Scraper")
def website_scraper(url: str) -> str:
    """Scrapes content from a given URL."""
    loader = WebBaseLoader(url)
    docs = loader.load()
    return "\n\n".join([doc.page_content for doc in docs])

# File Writer Tool (using a simple local write for demonstration)
@tool("File Writer")
def file_writer(file_path: str, content: str) -> str:
    """Writes content to a specified file path."""
    try:
        with open(file_path, 'w') as f:
            f.write(content)
        return f"Content successfully written to {file_path}"
    except Exception as e:
        return f"Error writing to file {file_path}: {e}"

# Search Tool for general information retrieval
ddgo_search = DuckDuckGoSearchAPIWrapper()
@tool("DuckDuckGo Search")
def duck_duck_go_search(query: str) -> str:
    """Searches the web using DuckDuckGo for a given query."""
    return ddgo_search.run(query)

print("Tools 'Website Scraper', 'File Writer', and 'DuckDuckGo Search' defined.")

from crewai import Agent

data_analyst = Agent(
    role='Data Analyst',
    goal='Understand a given topic, gather relevant information, and summarize it clearly',
    backstory=(
        "You are a highly skilled data analyst with a knack for identifying key information "
        "and presenting it in an understandable format. You excel at research and synthesis."
        "You are detail-oriented and always aim for accurate, comprehensive responses."
    ),
    verbose=True,
    allow_delegation=False, # For a single-agent setup, delegation isn't applicable
    tools=[website_scraper, file_writer, duck_duck_go_search],
    llm=llm
)

print("Data Analyst agent defined.")

from crewai import Task

understanding_task = Task(
    description=(
        "Research the current trends in Artificial Intelligence, focusing on recent advancements "
        "in large language models (LLMs) and their applications. "
        "Use the 'DuckDuckGo Search' tool to find relevant articles and then the 'Website Scraper' "
        "to extract content from interesting links. "
        "Finally, summarize your findings in a comprehensive report and save it to a file named 'ai_trends_report.md' "
        "using the 'File Writer' tool. "
        "Ensure the report covers at least 3 distinct trends or applications."
    ),
    agent=data_analyst,
    expected_output='A markdown report saved to `ai_trends_report.md` summarizing current AI and LLM trends with at least 3 distinct trends/applications covered.'
)

print("Understanding task defined for the Data Analyst.")

from crewai import Crew, Process

# Instantiate your crew
project_crew = Crew(
    agents=[data_analyst],
    tasks=[understanding_task],
    verbose=2, # You can set it to 1 or 2 to different logging levels
    process=Process.sequential # For a single agent, sequential process is appropriate
)

# Kick off the crew's work
print("Starting the Crew's work...")
result = project_crew.kickoff()

print("\n\n------------------------------")
print("Crew work finished. Here is the result:")
