import os
import re
from typing import List

import torch
from datasets import load_dataset
from peft import LoraConfig, PeftModel
from transformers import AutoModelForCausalLM, AutoTokenizer
from trl import GRPOConfig, GRPOTrainer

# ---------------------------------------------------------------------------
# 1. Config
# ---------------------------------------------------------------------------
BASE_MODEL = "Qwen/Qwen2.5-0.5B-Instruct"
OUTPUT_DIR = "./qwen-grpo-gsm8k"
N_TRAIN_SAMPLES = 200          # GSM8K has 7.5k train; subsample for demo speed
N_EVAL_SAMPLES = 50            # eval slice for the comparison at the end

SYSTEM_PROMPT = (
    "You are a math tutor. Solve the problem step by step. "
    "Put your final numeric answer between <answer> and </answer> tags."
)

# ---------------------------------------------------------------------------
# 2. Dataset prep — GSM8K
# ---------------------------------------------------------------------------
# GSM8K answers are formatted as "...explanation...\n#### 42". We extract the
# part after #### as the gold answer (a clean number string).
def extract_gold_answer(answer_field: str) -> str:
    """GSM8K stores the answer after the '####' marker."""
    m = re.search(r"####\s*([-\d,\.]+)", answer_field)
    return m.group(1).replace(",", "").strip() if m else ""


def to_chat_prompt(tokenizer, question: str) -> str:
    """Render the chat template to a plain string. GRPOTrainer will tokenize."""
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": question},
    ]
    return tokenizer.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=True
    )


def build_dataset(tokenizer, n_train: int):
    raw = load_dataset("openai/gsm8k", "main", split="train").shuffle(seed=42)
    raw = raw.select(range(n_train))

    def transform(row):
        return {
            "prompt": to_chat_prompt(tokenizer, row["question"]),
            "gold_answer": extract_gold_answer(row["answer"]),
        }

    # GRPOTrainer's contract: dataset must have a "prompt" column. Any other
    # columns are forwarded as kwargs to the reward function.
    return raw.map(transform, remove_columns=raw.column_names)

# ---------------------------------------------------------------------------
# 3. Reward functions
# ---------------------------------------------------------------------------
# GRPOTrainer accepts a list of reward funcs; their outputs are summed (or
# weighted-summed via reward_weights). Splitting into "format" + "correctness"
# is the DeepSeek-R1 trick: format reward gives the model a signal even when
# it can't yet solve the problem, preventing dead gradients early in training.

ANSWER_TAG_RE = re.compile(r"<answer>\s*([-\d\.,]+)\s*</answer>")
NUMBER_RE = re.compile(r"[-]?\d+(?:\.\d+)?")


def _extract_predicted(completion: str) -> str | None:
    """Pull the predicted number, preferring the tagged form."""
    m = ANSWER_TAG_RE.search(completion)
    if m:
        return m.group(1).replace(",", "").strip()
    # Fallback: last number anywhere in the completion
    nums = NUMBER_RE.findall(completion)
    return nums[-1] if nums else None


def _numeric_equal(a: str, b: str) -> bool:
    try:
        return abs(float(a) - float(b)) < 1e-6
    except (ValueError, TypeError):
        return False


def correctness_reward(completions: List[str], gold_answer: List[str], **kwargs):
    """+1 if predicted number matches gold, else 0. This is the dense signal."""
    rewards = []
    for completion, gold in zip(completions, gold_answer):
        pred = _extract_predicted(completion)
        rewards.append(1.0 if pred and _numeric_equal(pred, gold) else 0.0)
    return rewards


def format_reward(completions: List[str], **kwargs):
    """+0.5 for using the <answer>...</answer> tags; +0.2 for any number at all.
    Acts as a shaping reward so the policy gets gradient signal even before it
    starts solving problems correctly."""
    rewards = []
    for completion in completions:
        if ANSWER_TAG_RE.search(completion):
            rewards.append(0.5)
        elif NUMBER_RE.search(completion):
            rewards.append(0.2)
        else:
            rewards.append(0.0)
    return rewards

# ---------------------------------------------------------------------------
# 4. Train
# ---------------------------------------------------------------------------
def train():
    tokenizer = AutoTokenizer.from_pretrained(BASE_MODEL)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    train_ds = build_dataset(tokenizer, n_train=N_TRAIN_SAMPLES)
    print(f"Training set size: {len(train_ds)}")
    print(f"Sample prompt:\n{train_ds[0]['prompt'][:300]}\n")
    print(f"Sample gold:  {train_ds[0]['gold_answer']}\n")

    # LoRA: train ~5M params instead of 500M
    lora_config = LoraConfig(
        r=16,
        lora_alpha=32,
        lora_dropout=0.05,
        bias="none",
        task_type="CAUSAL_LM",
        target_modules=["q_proj", "k_proj", "v_proj", "o_proj",
                        "gate_proj", "up_proj", "down_proj"],
    )

    config = GRPOConfig(
        output_dir=OUTPUT_DIR,
        num_train_epochs=1,
        per_device_train_batch_size=2,
        gradient_accumulation_steps=4,        # effective batch = 8 prompts
        learning_rate=5e-6,                   # GRPO likes very low LR
        # ---- GRPO-specific ----
        num_generations=4,                    # G in "Group Relative" — completions per prompt
        max_completion_length=256,
        temperature=0.9,                      # exploration: higher = more diverse rollouts
        beta=0.04,                            # KL penalty against ref policy (anchor)
        # ---- weights for the two reward functions (length must match list below) ----
        reward_weights=[1.0, 0.3],            # correctness dominates; format is shaping
        # ---- infra ----
        bf16=torch.cuda.is_available(),
        gradient_checkpointing=True,
        logging_steps=2,
        save_strategy="epoch",
        report_to="none",
    )

    trainer = GRPOTrainer(
        model=BASE_MODEL,
        reward_funcs=[correctness_reward, format_reward],
        args=config,
        train_dataset=train_ds,
        processing_class=tokenizer,
        peft_config=lora_config,
    )

    trainer.train()
    trainer.save_model(OUTPUT_DIR)
    print(f"Saved LoRA adapter to {OUTPUT_DIR}")


# ---------------------------------------------------------------------------
# 5. Evaluation: base vs GRPO vs OpenAI on a held-out slice
# ---------------------------------------------------------------------------
def _generate(model, tokenizer, prompt: str, max_new_tokens: int = 256) -> str:
    inputs = tokenizer(prompt, return_tensors="pt").to(model.device)
    with torch.no_grad():
        out = model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            do_sample=False,
            pad_token_id=tokenizer.eos_token_id,
        )
    return tokenizer.decode(out[0][inputs["input_ids"].shape[1]:],
                            skip_special_tokens=True)


def _accuracy(predictions: List[str], golds: List[str]) -> float:
    correct = 0
    for pred, gold in zip(predictions, golds):
        extracted = _extract_predicted(pred)
        if extracted and _numeric_equal(extracted, gold):
            correct += 1
    return correct / len(golds)


def evaluate():
    """Compare three models on the same GSM8K test slice:
       (a) Qwen2.5-0.5B base, (b) Qwen2.5-0.5B + GRPO LoRA, (c) OpenAI gpt-4o-mini."""
    tokenizer = AutoTokenizer.from_pretrained(BASE_MODEL)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    test_raw = load_dataset("openai/gsm8k", "main", split="test").shuffle(seed=7)
    test_raw = test_raw.select(range(N_EVAL_SAMPLES))
    questions = [r["question"] for r in test_raw]
    golds = [extract_gold_answer(r["answer"]) for r in test_raw]
    prompts = [to_chat_prompt(tokenizer, q) for q in questions]

    # ---- (a) Base Qwen ----
    print("\n[a] Evaluating base Qwen ...")
    base = AutoModelForCausalLM.from_pretrained(
        BASE_MODEL,
        torch_dtype=torch.bfloat16 if torch.cuda.is_available() else torch.float32,
        device_map="auto" if torch.cuda.is_available() else None,
    )
    base.eval()
    base_preds = [_generate(base, tokenizer, p) for p in prompts]
    base_acc = _accuracy(base_preds, golds)
    print(f"    base accuracy: {base_acc:.2%}")

    # ---- (b) GRPO-trained ----
    print("\n[b] Evaluating GRPO-trained Qwen ...")
    grpo_model = PeftModel.from_pretrained(base, OUTPUT_DIR)
    grpo_model.eval()
    grpo_preds = [_generate(grpo_model, tokenizer, p) for p in prompts]
    grpo_acc = _accuracy(grpo_preds, golds)
    print(f"    GRPO accuracy: {grpo_acc:.2%}")

    # ---- (c) OpenAI baseline (reference, not trained) ----
    print("\n[c] Evaluating OpenAI gpt-4o-mini (reference) ...")
    openai_acc = None
    if os.environ.get("OPENAI_API_KEY"):
        from openai import OpenAI
        client = OpenAI()
        openai_preds = []
        for q in questions:
            resp = client.chat.completions.create(
                model="gpt-4o-mini",
                messages=[
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": q},
                ],
                temperature=0.0,
            )
            openai_preds.append(resp.choices[0].message.content)
        openai_acc = _accuracy(openai_preds, golds)
        print(f"    gpt-4o-mini accuracy: {openai_acc:.2%}")
    else:
        print("    (skipped — set OPENAI_API_KEY to include this baseline)")

    # ---- summary ----
    print("\n" + "=" * 60)
    print("GSM8K accuracy on", N_EVAL_SAMPLES, "held-out problems:")
    print(f"  Base Qwen2.5-0.5B-Instruct : {base_acc:.2%}")
    print(f"  + GRPO (LoRA, {N_TRAIN_SAMPLES} prompts) : {grpo_acc:.2%}  "
          f"(Δ = {(grpo_acc - base_acc) * 100:+.1f} pts)")
    if openai_acc is not None:
        print(f"  OpenAI gpt-4o-mini (ref)   : {openai_acc:.2%}")
    print("=" * 60)


