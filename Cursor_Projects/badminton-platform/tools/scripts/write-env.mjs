// Writes apps/web/.env.local from the running local Supabase stack.
// Usage (from the project folder, after `pnpm db:start`):  pnpm env:local
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

let status;
try {
  status = JSON.parse(execSync('npx supabase status -o json', { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }));
} catch (e) {
  console.error('Could not read the local Supabase status. Is Docker Desktop running, and did you run "pnpm db:start"?');
  console.error(String(e.stderr || e.message).trim());
  process.exit(1);
}
const url = status.API_URL;
const key = status.PUBLISHABLE_KEY || status.ANON_KEY;
const dbUrl = status.DB_URL;
const mail = status.MAILPIT_URL || status.INBUCKET_URL || 'http://127.0.0.1:54324';
if (!url || !key || !dbUrl) {
  console.error('Supabase status is missing API_URL, keys or DB_URL:', Object.keys(status).join(', '));
  process.exit(1);
}
writeFileSync(
  'apps/web/.env.local',
  [
    '# Generated by `pnpm env:local` for LOCAL development only. Never commit this file.',
    `NEXT_PUBLIC_SUPABASE_URL=${url}`,
    `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${key}`,
    `DATABASE_URL=${dbUrl}`,
    `LOCAL_MAILBOX_URL=${mail}`,
    '# App emails (invitations) go to the same local test mailbox.',
    'SMTP_URL=smtp://127.0.0.1:54325',
    '',
  ].join('\n'),
);
console.log('Wrote apps/web/.env.local');
console.log(`Test mailbox (sign-in emails): ${mail}`);
