# 6. COMPOSITE METRIC (regulation coverage + LLM-judged correctness)
# ============================================================
JUDGE_PROMPT = """You are evaluating an answer to a financial compliance question.

Question: {question}
Reference answer: {reference}
Predicted answer: {prediction}

Score the prediction on factual correctness vs the reference, on a scale of 0.0 to 1.0.
- 1.0 = factually equivalent and complete
- 0.5 = partially correct or missing key detail
- 0.0 = wrong or contradictory

Respond with ONLY a single decimal number between 0.0 and 1.0."""


def llm_judge(example, pred) -> float:
    """LLM-as-judge correctness score."""
    try:
        prompt = JUDGE_PROMPT.format(
            question=example.question,
            reference=example.answer,
            prediction=pred.answer,
        )
        # Use the task LM directly for judging
        out = task_lm(prompt)[0].strip()
        return float(out.split()[0])
    except Exception:
        return 0.0


def reg_coverage(example, pred) -> float:
    """Fraction of required regulations cited in the answer."""
    if not example.required_regs:
        return 1.0
    ans = pred.answer.lower()
    hits = sum(1 for r in example.required_regs if r.lower() in ans)
    return hits / len(example.required_regs)


def composite_metric(example, pred, trace=None) -> float:
    """Weighted: 70% LLM-judged correctness, 30% regulation citation coverage."""
    correctness = llm_judge(example, pred)
    coverage = reg_coverage(example, pred)
    score = 0.7 * correctness + 0.3 * coverage
    # When trace is not None, MIPROv2 is checking demonstration quality —
    # use a stricter threshold for what counts as a "good" trace.
    if trace is not None:
        return score >= 0.7
    return score

