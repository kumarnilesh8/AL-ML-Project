class EmbeddingRetriever(dspy.Retrieve):
    """In-memory dense retriever using OpenAI embeddings + cosine similarity."""

    def __init__(self, corpus, k=4, model="text-embedding-3-small"):
        super().__init__(k=k)
        self.corpus = corpus
        self.client = OpenAI()
        self.model = model
        # Pre-compute corpus embeddings
        resp = self.client.embeddings.create(model=model, input=corpus)
        self.doc_embeds = np.array([d.embedding for d in resp.data])
        # L2 normalize for cosine via dot product
        self.doc_embeds /= np.linalg.norm(self.doc_embeds, axis=1, keepdims=True)

    def forward(self, query, k=None):
        k = k or self.k
        q = self.client.embeddings.create(model=self.model, input=[query]).data[0].embedding
        q = np.array(q)
        q /= np.linalg.norm(q)
        scores = self.doc_embeds @ q
        top_idx = np.argsort(-scores)[:k]
        return dspy.Prediction(passages=[self.corpus[i] for i in top_idx])


