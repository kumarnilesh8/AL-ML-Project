# 4. MULTI-HOP RAG MODULE
# ============================================================
class DecomposeQuery(dspy.Signature):
    """Break down a complex compliance question into 2-3 focused sub-questions
    that can each be answered by retrieving specific regulatory passages."""
    question: str = dspy.InputField()
    sub_questions: list[str] = dspy.OutputField(desc="2-3 atomic sub-questions")


class SynthesizeAnswer(dspy.Signature):
    """Given a complex compliance question and retrieved evidence from
    multiple sub-queries, produce a precise, well-cited answer.
    Cite specific regulations (e.g., FATF Rec 10, MAS Notice 626) when relevant."""
    question: str = dspy.InputField()
    evidence: str = dspy.InputField(desc="Retrieved passages from sub-queries")
    answer: str = dspy.OutputField(desc="Concise, accurate, regulation-cited answer")


class MultiHopComplianceRAG(dspy.Module):
    def __init__(self, retriever, k=4):
        super().__init__()
        self.retriever = retriever
        self.decompose = dspy.ChainOfThought(DecomposeQuery)
        self.synthesize = dspy.ChainOfThought(SynthesizeAnswer)
        self.k = k

    def forward(self, question):
        # Hop 1: decompose
        decomp = self.decompose(question=question)
        sub_qs = decomp.sub_questions or [question]

        # Hop 2: retrieve evidence per sub-question
        evidence_blocks = []
        for sq in sub_qs[:3]:
            passages = self.retriever(sq).passages
            evidence_blocks.append(f"Sub-Q: {sq}\n" + "\n".join(f"  - {p}" for p in passages))
        evidence = "\n\n".join(evidence_blocks)

        # Hop 3: synthesize
        result = self.synthesize(question=question, evidence=evidence)
        return dspy.Prediction(
            answer=result.answer,
            sub_questions=sub_qs,
            evidence=evidence,
        )


