class SimpleRetriever(dspy.Retrieve):
    def __init__(self, corpus, k=3):
        super().__init__(k=k)
        self.corpus = corpus

    def forward(self, query, k=None):
        k = k or self.k
        q_terms = set(query.lower().split())
        scored = [
            (len(q_terms & set(doc.lower().split())), doc)
            for doc in self.corpus
        ]
        scored.sort(key=lambda x: x[0], reverse=True)
        passages = [doc for _, doc in scored[:k]]
        return dspy.Prediction(passages=passages)

